/**
 * Folds apps/e2e/local-e2e-runs/amazon/results.jsonl (latest result per
 * region and point) and the checklist docs/manual-testing/10-amazon.md into
 * docs/plans/amazon-e2e-results.md. Screenshots stay untracked scratch; the
 * table names their path.
 *
 *   node apps/e2e/scripts/amazon-results-table.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const doc = readFileSync(resolve(root, 'docs/manual-testing/10-amazon.md'), 'utf8');
const points = new Map();
for (const m of doc.matchAll(/^(\d+)\. \[ \] `([a-z-]+)` \*\*(.+?)\*\*/gm)) points.set(Number(m[1]), { kind: m[2], title: m[3].replace(/\.$/, '') });

const resultsFile = resolve(root, 'apps/e2e/local-e2e-runs/amazon/results.jsonl');
const latest = new Map();
if (existsSync(resultsFile)) {
  for (const line of readFileSync(resultsFile, 'utf8').split('\n').filter(Boolean)) {
    const d = JSON.parse(line);
    latest.set(`${d.region}:${d.point}`, d);
  }
}
const cell = (region, p) => {
  const d = latest.get(`${region}:${p}`);
  if (!d) return '-';
  const sim = /simulated|SIMULATED/i.test(d.note) ? ' (simulated)' : '';
  return d.result === 'pass' ? `pass${sim}` : d.result === 'fail' ? 'FAIL' : d.result;
};
let pass = 0;
let fail = 0;
let none = 0;
const rows = [];
for (const [p, info] of [...points].sort((a, b) => a[0] - b[0])) {
  const regions = ['eu', 'na', 'fe'].map((r) => cell(r, p));
  const any = regions.find((c) => c !== '-');
  const shot = ['eu', 'na', 'fe'].map((r) => latest.get(`${r}:${p}`)?.screenshot).find(Boolean) ?? '';
  const note = ['eu', 'na', 'fe'].map((r) => latest.get(`${r}:${p}`)).find((d) => d && d.result === 'fail')?.note ?? '';
  if (!any) none += 1;
  else if (regions.some((c) => c === 'FAIL')) fail += 1;
  else pass += 1;
  rows.push(`| ${p} | ${info.kind} | ${info.title.replace(/\|/g, '/')} | ${regions.join(' | ')} | ${shot ? shot.replace(root + '/', '') : ''} | ${note.replace(/\|/g, '/').slice(0, 160)} |`);
}
const out = `# Amazon E2E results (layer 1: fake SP-API)

Generated by apps/e2e/scripts/amazon-results-table.mjs from the last run. Screenshots live in apps/e2e/local-e2e-runs/amazon/<region>/<point>.png (untracked scratch).

"simulated" means the fake server played Amazon (buyer, feeds, reports, MCF, SQS): such a pass proves OpenLinker's side only. A cell of - means the point was not run for that region.

Points: ${points.size}. With at least one result and no failure: ${pass}. With a failure: ${fail}. Not run: ${none}.

| point | kind | what | EU | NA | FE | screenshot | failure note |
|---|---|---|---|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync(resolve(root, 'docs/plans/amazon-e2e-results.md'), out);
console.log(`points ${points.size}: pass ${pass}, fail ${fail}, not run ${none}`);
