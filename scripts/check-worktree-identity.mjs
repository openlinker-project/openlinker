#!/usr/bin/env node
/**
 * check-worktree-identity
 *
 * A pre-commit hook is a statement about the commit it gates. #2767 reports a
 * hook whose lint / `check:invariants` output named a SIBLING worktree's paths:
 * the gate then described a tree that was not being committed, so a green hook
 * proved nothing and a red one sent the author chasing a defect they did not
 * introduce.
 *
 * WHAT THIS PROVES. That the tree the hook runs in is the tree whose code the
 * tools will resolve:
 *
 *   1. the working directory is the git toplevel (real paths compared);
 *   2. `node_modules` exists and resolves inside this toplevel;
 *   3. every workspace link under `node_modules/@openlinker/*` resolves inside
 *      this toplevel, as does every `apps/*` / `libs/*` `node_modules` directory;
 *   4. at least one workspace link was observed.
 *
 * Rule 3 is the one that matters: copying or symlinking `node_modules` from a
 * sibling worktree to skip an install is the most plausible way to make eslint
 * and tsc report another tree's paths, because pnpm's workspace links then point
 * at the sibling's packages. Rule 2 reports a missing install rather than
 * skipping it: with no `node_modules` plain `node` resolves UPWARD, into the main
 * checkout (or a parent worktree, for a nested one) - measured, not assumed.
 *
 * WHAT THIS DOES NOT PROVE. The exact trigger in the reporter's run is not
 * recoverable and is not claimed. And a worktree that never ran `pnpm install`
 * has no `.husky/_` at all (it is generated by the `prepare` script and is
 * untracked), so git finds no hook and nothing runs - this script cannot help
 * there, because it is itself invoked BY the hook.
 *
 * "MATCHED NOTHING" - rule 4 exists because a scan that observed no link at all
 * would otherwise pass: the failure this repo has been bitten by repeatedly.
 *
 * FAILS LOUDLY. Exit 1 names every offending path and the remedy. There is no
 * bypass flag beyond git's own `--no-verify`; a hook that cannot tell which tree
 * it is in must not report success.
 *
 * Usage:
 *   node scripts/check-worktree-identity.mjs
 *   node scripts/check-worktree-identity.mjs --self-check
 */

import { execFileSync } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  realpathSync,
  rmSync,
  symlinkSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join, sep } from 'node:path';

/** Is `child` the same path as `parent`, or inside it? Segment-aware: no bare prefix match. */
export function isInside(parent, child) {
  return child === parent || child.startsWith(parent + sep);
}

/**
 * The rules, over facts already gathered - pure, so `--self-check` can prove each
 * one without a git repository.
 *
 * facts: {
 *   toplevel:       real path of the git toplevel
 *   cwd:            real path of the working directory
 *   nodeModules:    real path of <toplevel>/node_modules, or null when absent
 *   workspaceLinks: [{ name, real }] for node_modules/@openlinker/*
 *   packageModules: [{ dir, real }] for apps|libs/<pkg>/node_modules that exist
 * }
 */
export function evaluateWorktreeIdentity(facts) {
  const problems = [];
  const { toplevel, cwd, nodeModules, workspaceLinks, packageModules } = facts;

  if (cwd !== toplevel) {
    problems.push(
      `the working directory (${cwd}) is not the git toplevel (${toplevel}), so lint and the ` +
        'tests would run in a different tree than the one being committed'
    );
  }

  if (nodeModules === null) {
    problems.push(
      'node_modules is missing, so node would resolve dependencies upward into another ' +
        'checkout - run `pnpm install` in THIS worktree'
    );
  } else if (!isInside(toplevel, nodeModules)) {
    problems.push(
      `node_modules resolves to ${nodeModules}, outside this tree (${toplevel}) - it is a link ` +
        'or copy from another worktree'
    );
  }

  for (const { name, real } of workspaceLinks) {
    if (!isInside(toplevel, real)) {
      problems.push(
        `node_modules/@openlinker/${name} resolves to ${real}, outside this tree (${toplevel}) - ` +
          'eslint and tsc would validate that tree instead'
      );
    }
  }

  for (const { dir, real } of packageModules) {
    if (!isInside(toplevel, real)) {
      problems.push(`${dir}/node_modules resolves to ${real}, outside this tree (${toplevel})`);
    }
  }

  // Only meaningful once node_modules exists; a missing install is already reported.
  if (nodeModules !== null && workspaceLinks.length === 0) {
    problems.push(
      'no workspace link was found under node_modules/@openlinker, so nothing proves which ' +
        'tree the packages resolve to - the install is incomplete (a scan that observes nothing ' +
        'must not pass)'
    );
  }

  return problems;
}

/** Real path, or null when it does not exist. */
function realOrNull(path) {
  try {
    return realpathSync(path);
  } catch {
    return null;
  }
}

/** Gather the facts for `toplevelPath` from the filesystem. */
export function collectWorktreeFacts(toplevelPath, cwdPath = process.cwd()) {
  const toplevel = realpathSync(toplevelPath);
  const cwd = realpathSync(cwdPath);
  const nodeModules = realOrNull(join(toplevel, 'node_modules'));

  const workspaceLinks = [];
  const scopeDir = join(toplevel, 'node_modules', '@openlinker');
  if (existsSync(scopeDir)) {
    for (const name of readdirSync(scopeDir)) {
      const real = realOrNull(join(scopeDir, name));
      if (real !== null) workspaceLinks.push({ name, real });
    }
  }

  const packageModules = [];
  for (const group of ['apps', 'libs']) {
    const groupDir = join(toplevel, group);
    if (!existsSync(groupDir)) continue;
    for (const pkg of readdirSync(groupDir)) {
      const nm = join(groupDir, pkg, 'node_modules');
      const real = realOrNull(nm);
      if (real !== null) packageModules.push({ dir: `${group}/${pkg}`, real });
    }
  }

  return { toplevel, cwd, nodeModules, workspaceLinks, packageModules };
}

function main() {
  let toplevel;
  try {
    toplevel = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim();
  } catch {
    console.error(
      '✗ check-worktree-identity: cannot determine the git toplevel, so it cannot be shown ' +
        'which tree this hook validates (#2767). Refusing to report success.'
    );
    process.exit(1);
  }

  const problems = evaluateWorktreeIdentity(collectWorktreeFacts(toplevel));
  if (problems.length === 0) {
    console.log(
      `✓ check-worktree-identity: this hook and its dependencies are all inside ${toplevel}.`
    );
    return;
  }

  console.error('✗ check-worktree-identity failed (#2767):\n');
  for (const problem of problems) console.error(`  - ${problem}`);
  console.error(
    '\nA hook that cannot show it is validating THIS worktree must not report success. Fix the ' +
      'problem above and commit again. For a node_modules problem, run `pnpm install` in this ' +
      'worktree (do not copy or link node_modules from another one).'
  );
  process.exit(1);
}

// ---------------------------------------------------------------------------
// --self-check
// ---------------------------------------------------------------------------

function selfCheck() {
  const failures = [];
  const eq = (label, actual, expected) => {
    if (JSON.stringify(actual) !== JSON.stringify(expected)) {
      failures.push(
        `  ${label}: expected ${JSON.stringify(expected)}, got ${JSON.stringify(actual)}`
      );
    }
  };

  const T = '/work/a';
  const healthy = {
    toplevel: T,
    cwd: T,
    nodeModules: `${T}/node_modules`,
    workspaceLinks: [{ name: 'core', real: `${T}/libs/core` }],
    packageModules: [{ dir: 'apps/web', real: `${T}/apps/web/node_modules` }],
  };

  // --- pure rules ------------------------------------------------------------
  eq('a healthy tree passes', evaluateWorktreeIdentity(healthy).length, 0);
  eq(
    'a different working directory fails',
    evaluateWorktreeIdentity({ ...healthy, cwd: '/work/a/apps/web' }).length,
    1
  );
  eq(
    'node_modules inside a sibling fails',
    evaluateWorktreeIdentity({ ...healthy, nodeModules: '/work/b/node_modules' }).length,
    1
  );
  eq(
    'a missing node_modules fails (reported, never skipped)',
    evaluateWorktreeIdentity({ ...healthy, nodeModules: null, workspaceLinks: [] }).length,
    1
  );
  eq(
    'a workspace link into a sibling fails',
    evaluateWorktreeIdentity({
      ...healthy,
      workspaceLinks: [
        { name: 'core', real: `${T}/libs/core` },
        { name: 'shared', real: '/work/b/libs/shared' },
      ],
    }).length,
    1
  );
  eq(
    'a package node_modules into a sibling fails',
    evaluateWorktreeIdentity({
      ...healthy,
      packageModules: [{ dir: 'apps/api', real: '/work/b/apps/api/node_modules' }],
    }).length,
    1
  );
  eq(
    'no workspace link at all fails: a scan that observed nothing must not pass',
    evaluateWorktreeIdentity({ ...healthy, workspaceLinks: [] }).length,
    1
  );
  eq(
    'a sibling whose name merely starts the same is outside',
    isInside('/work/a', '/work/ab'),
    false
  );
  eq('the tree itself is inside', isInside('/work/a', '/work/a'), true);
  eq('a nested path is inside', isInside('/work/a', '/work/a/libs/core'), true);

  // --- real filesystem: the actual defect, symlinked node_modules -------------
  const base = mkdtempSync(join(tmpdir(), 'ol-worktree-identity-'));
  try {
    const makeTree = (name) => {
      const root = join(base, name);
      mkdirSync(join(root, 'libs', 'core'), { recursive: true });
      mkdirSync(join(root, 'node_modules', '@openlinker'), { recursive: true });
      symlinkSync(
        join('..', '..', 'libs', 'core'),
        join(root, 'node_modules', '@openlinker', 'core')
      );
      return root;
    };

    const a = makeTree('a');
    const b = makeTree('b');
    eq(
      'real tree: its own links pass',
      evaluateWorktreeIdentity(collectWorktreeFacts(a, a)).length,
      0
    );

    // The scenario #2767 is about: a tree that reuses a sibling's node_modules.
    const c = join(base, 'c');
    mkdirSync(join(c, 'libs', 'core'), { recursive: true });
    symlinkSync(join(b, 'node_modules'), join(c, 'node_modules'));
    const linked = evaluateWorktreeIdentity(collectWorktreeFacts(c, c));
    eq('real tree: node_modules symlinked from a sibling fails', linked.length >= 1, true);

    // Same sibling's links, copied rather than linked wholesale.
    const d = join(base, 'd');
    mkdirSync(join(d, 'libs', 'core'), { recursive: true });
    mkdirSync(join(d, 'node_modules', '@openlinker'), { recursive: true });
    symlinkSync(join(b, 'libs', 'core'), join(d, 'node_modules', '@openlinker', 'core'));
    eq(
      'real tree: a workspace link pointing into a sibling fails',
      evaluateWorktreeIdentity(collectWorktreeFacts(d, d)).length,
      1
    );

    const e = join(base, 'e');
    mkdirSync(join(e, 'libs', 'core'), { recursive: true });
    eq(
      'real tree: no node_modules fails',
      evaluateWorktreeIdentity(collectWorktreeFacts(e, e)).length,
      1
    );
  } finally {
    rmSync(base, { recursive: true, force: true });
  }

  if (failures.length > 0) {
    console.error('✗ check-worktree-identity --self-check failed:\n');
    for (const f of failures) console.error(f);
    process.exit(1);
  }
  console.log(
    '✓ check-worktree-identity --self-check: rules and the symlinked-node_modules case behave.'
  );
}

if (process.argv.includes('--self-check')) {
  selfCheck();
} else {
  main();
}
